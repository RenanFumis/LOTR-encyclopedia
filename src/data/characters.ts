function assertDex(list: Character[]): void {
  const problems: string[] = [];
  const ids = new Set<string>();
  const numbers = new Set<number>();

  for (const character of list) {
    if (ids.has(character.id)) problems.push(`id repetido: ${character.id}`);
    ids.add(character.id);
    if (numbers.has(character.number)) problems.push(`número repetido: ${character.number}`);
    numbers.add(character.number);
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(character.id)) problems.push(`id inválido: ${character.id}`);

    for (const key of STAT_KEYS) {
      const value = character.stats[key];
      if (value < 1 || value > 100) problems.push(`${character.id} · ${key} fora da escala`);
    }

    const first = character.forms?.[0];
    if (first) {
      for (const key of STAT_KEYS) {
        if (first.stats[key] !== character.stats[key]) {
          problems.push(`${character.id} difere da forma ${first.id}`);
        }
      }
    }

    for (const form of character.forms ?? []) {
      for (const key of STAT_KEYS) {
        const value = form.stats[key];
        if (value < 1 || value > 100) problems.push(`${character.id}/${form.id} · ${key}`);
      }
    }
  }

  for (let number = 0; number < list.length; number += 1) {
    if (!numbers.has(number)) problems.push(`falta o número ${number}`);
  }

  for (const character of list) {
    for (const related of character.related) {
      if (!ids.has(related)) problems.push(`${character.id} aponta para ${related}`);
      if (related === character.id) problems.push(`${character.id} aponta para si`);
    }
  }

  if (problems.length > 0) {
    throw new Error(`Lorthdex inconsistente:\n${problems.join("\n")}`);
  }
}

if (import.meta.env.DEV) assertDex(characters);

export const charactersById: Record<string, Character> = Object.fromEntries(
  characters.map((character) => [character.id, character]),
);

export function getCharacter(id: string): Character | undefined {
  return Object.prototype.hasOwnProperty.call(charactersById, id) ? charactersById[id] : undefined;
}
